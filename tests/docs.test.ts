import { describe, it, expect, afterAll } from 'vitest'
import fs from 'fs'
import os from 'os'
import path from 'path'
import ExcelJS from 'exceljs'
import { buildSpreadsheet, buildReportPdf, getDocument, listDocuments } from '@/lib/docs/generate'
import { collectInfraSections, infraSummaryMarkdown } from '@/lib/docs/infra'
import { extractAll, hidePartialMarker } from '@/lib/motion/inline'

const tmp = process.env.JARVIS_DATA_DIR!

describe('buildSpreadsheet', () => {
  it('writes a real .xlsx that can be re-opened', async () => {
    const meta = await buildSpreadsheet({
      name: 'Relatório de Vendas Q4',
      sheets: [
        { name: 'Vendas', headers: ['Mês', 'Unidades', 'Receita'], rows: [['Outubro', 120, 45000], ['Novembro', 145, 52000]], totals: true },
      ],
    })
    expect(meta.kind).toBe('xlsx')
    expect(meta.size).toBeGreaterThan(1000)
    const wb = new ExcelJS.Workbook()
    await wb.xlsx.readFile(path.join(tmp, 'documents', meta.file))
    const ws = wb.getWorksheet('Vendas')
    expect(ws).toBeDefined()
    expect(ws!.getCell('A1').value).toBe('Mês')
    expect(ws!.getCell('A2').value).toBe('Outubro')
    expect(ws!.getCell('C3').value).toBe(52000)
    // totals row
    expect(String(ws!.getCell('C4').value && (ws!.getCell('C4').value as { formula?: string }).formula || '')).toContain('SUM')
    expect(getDocument(meta.file)?.title).toContain('Relatório de Vendas')
  })

  it('rejects empty sheets with a clear error', async () => {
    await expect(buildSpreadsheet({ sheets: [{ name: 'x', headers: [], rows: [] }] })).rejects.toThrow(/cabeçalhos/)
  })

  it('sanitizes sheet names and caps rows', async () => {
    const meta = await buildSpreadsheet({ sheets: [{ name: 'aba/com:caracteres*invalidos', headers: ['A'], rows: Array.from({ length: 5 }, (_, i) => [i]) }] })
    const wb = new ExcelJS.Workbook()
    await wb.xlsx.readFile(path.join(tmp, 'documents', meta.file))
    expect(wb.worksheets[0].name).not.toMatch(/[\\/?*[\]:]/)
  })
})

describe('buildReportPdf', () => {
  it('writes a PDF with sections and page footer', async () => {
    const meta = await buildReportPdf({
      title: 'Relatório de Teste',
      subtitle: 'Subtítulo de exemplo',
      sections: [
        { heading: 'Resumo executivo', body: 'Texto corrido do resumo.\n\n- Item um\n- Item dois' },
        { heading: 'Detalhes', body: '# Subtítulo interno\nLinha normal de conteúdo com acentos: ção ã õ é.' },
      ],
    })
    expect(meta.kind).toBe('pdf')
    expect(meta.size).toBeGreaterThan(1500)
    const buf = fs.readFileSync(path.join(tmp, 'documents', meta.file))
    expect(buf.subarray(0, 5).toString()).toBe('%PDF-')
    expect(buf.includes(Buffer.from('/Type /Page'))).toBe(true)
    expect(getDocument(meta.file)?.title).toBe('Relatório de Teste')
  })

  it('requires at least one section', async () => {
    await expect(buildReportPdf({ title: 'vazio', sections: [] })).rejects.toThrow(/seção/)
  })
})

describe('infra report', () => {
  it('collects real sections about this machine', () => {
    const sections = collectInfraSections()
    expect(sections.length).toBeGreaterThanOrEqual(4)
    const headings = sections.map(s => s.heading).join('|')
    expect(headings).toMatch(/Sistema operacional|Memória|Provedores|Skill Engine/)
    for (const s of sections) expect(s.body.length).toBeGreaterThan(10)
  })

  it('renders a markdown summary with every section', () => {
    const md = infraSummaryMarkdown()
    expect(md).toContain('Relatório de infraestrutura')
    expect(md).toContain('###')
  })
})

describe('inline media markers (documents)', () => {
  it('extracts document markers and cleans the text', () => {
    const raw = 'Planilha pronta: Vendas.xlsx\n\n[[document:vendas-abc12345.xlsx]]'
    const { clean, documents, motionJobs } = extractAll(raw)
    expect(documents).toEqual(['vendas-abc12345.xlsx'])
    expect(motionJobs).toEqual([])
    expect(clean).not.toContain('[[document:')
  })

  it('handles motion and document markers in one message', () => {
    const a = '11111111-2222-4333-8444-555555555555'
    const { clean, motionJobs, documents } = extractAll(`vídeo [[motion:${a}]] e planilha [[document:xpto-11223344.xlsx]]`)
    expect(motionJobs).toEqual([a])
    expect(documents).toEqual(['xpto-11223344.xlsx'])
    expect(clean).not.toContain('[[')
  })

  it('hides partial document markers while streaming', () => {
    expect(hidePartialMarker('Planilha pronta')).toBe('Planilha pronta')
    expect(hidePartialMarker('texto [[doc')).toBe('texto ')
    expect(hidePartialMarker('texto [[document:plan')).toBe('texto ')
    expect(hidePartialMarker('texto [[document:vendas-abc12345.xlsx]]')).toBe('texto [[document:vendas-abc12345.xlsx]]')
  })
})

afterAll(() => {
  // Documents generated by these tests are intentionally left in the temp data dir; tests never touch real data
  void os.tmpdir
})
